import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { defineConfig } from 'vite';
import { svelte } from '@sveltejs/vite-plugin-svelte';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

function walkRelFiles(dir, baseDir = dir) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    const stat = fs.statSync(full);
    if (stat.isDirectory()) {
      out.push(...walkRelFiles(full, baseDir));
    } else {
      const rel = path.relative(baseDir, full).replace(/\\/g, '/');
      if (rel === 'sw.js' || rel.endsWith('.map')) continue;
      out.push('./' + rel);
    }
  }
  return out.sort();
}

function offlinePwaSwPlugin() {
  return {
    name: 'radiodiary-offline-sw',
    apply: 'build',
    closeBundle() {
      const outDir = path.resolve(__dirname, 'dist');
      if (!fs.existsSync(outDir)) return;
      const pkg = JSON.parse(fs.readFileSync(path.resolve(__dirname, 'package.json'), 'utf8'));
      const files = walkRelFiles(outDir);
      const precacheUrls = ['./', ...files];
      const hash = crypto
        .createHash('sha256')
        .update(pkg.version + ':' + precacheUrls.join('|'))
        .digest('hex')
        .slice(0, 8);
      const cacheName = `radiodiary-pwa-v${pkg.version}-${hash}`;

      const swCode = `/* Auto-generated by Vite build for offline-first Web PWA */
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE_URLS = ${JSON.stringify(precacheUrls, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(
        keys
          .filter((k) => k.startsWith('radiodiary-pwa-') && k !== CACHE_NAME)
          .map((k) => caches.delete(k))
      ))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);
  // 绝不拦截外部请求（如用户手动点击「检查更新」向 GitHub 查询版本）
  if (url.origin !== self.location.origin) return;

  // 页面导航：优先网络获取新版，离线或失败时精确回退该代预缓存的 index.html（不跨代覆写防资源错配）
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req).catch(() => caches.match('./index.html').then((r) => r || caches.match('./')))
    );
    return;
  }

  // 静态资源：命中本地缓存直接返回；未命中则联网抓取并写入缓存
  event.respondWith(
    caches.match(req, { ignoreSearch: false }).then((cached) => {
      if (cached) return cached;
      return fetch(req).then((res) => {
        if (res && res.ok && res.type === 'basic') {
          const copy = res.clone();
          caches.open(CACHE_NAME).then((c) => c.put(req, copy)).catch(() => {});
        }
        return res;
      });
    })
  );
});
`;
      fs.writeFileSync(path.join(outDir, 'sw.js'), swCode, 'utf8');
    },
  };
}

export default defineConfig({
  plugins: [svelte(), offlinePwaSwPlugin()],
  base: './', // 必须：Android assets.local 下没有域名根
  build: {
    outDir: 'dist',
    target: ['es2020', 'chrome80', 'safari14'], // 兼容 Android 10+ / 更新过 WebView 的老机与 iOS Safari 14+
    assetsInlineLimit: 2048,
    modulePreload: false, // 禁用 modulePreload，消除 Android WebView MIME 拦截风险
    sourcemap: false,
  },
  worker: { format: 'es' }, // analysis-worker 保持 module worker
});
